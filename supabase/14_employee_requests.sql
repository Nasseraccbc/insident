-- ============================================================================
--  ملف 14: بيانات طلب الموظف على المهمة
--
--  طلب الضيافة وتجهيز القاعة ليسا سطرًا في «الوصف»: أصناف بكمياتها، عدد
--  حضور، ترتيب قاعة، وقت بدء وانتهاء. وضغطها في نصّ حرّ يعني أن يعيد
--  الباريستا قراءتها وتأويلها — والخطأ فيها يُقدَّم على طاولة اجتماع.
--
--  فتُحفظ كما أدخلها الموظف في عمود مستقل، ومنه تُملأ حقول النموذج نفسها
--  حين يفتحه المنفّذ. مصدر واحد، بلا إعادة كتابة.
--
--  ولا تحتاج سياسة جديدة: tasks_report تشترط هيئة البلاغ (معلّق · بلا
--  مُسنَد إليه · بلا سجل) ولا تمسّ بقية الأعمدة.
-- ============================================================================

alter table tasks add column if not exists request jsonb not null default '{}'::jsonb;

comment on column tasks.request is
  'بيانات الطلب كما أدخلها صاحبه — تُملأ منها حقول النموذج عند التنفيذ';
